"""Audit the untouched educational scaffold and print its student inventory."""

import ast
import json
from pathlib import Path

import nbformat

ROOT = Path(__file__).resolve().parents[1]
MARKER = "TODO(" + "STUDENT-ML)"
EXPERIMENTS = {
    "01 — Bag of Words + Naive Bayes": [
        "preprocessing/text.py",
        "preprocessing/tokenization.py",
        "representations/vocabulary.py",
        "representations/bow.py",
        "training/priors.py",
        "training/probabilities.py",
        "training/smoothing.py",
        "models/naive_bayes.py",
        "evaluation/metrics.py",
    ],
    "02 — TF-IDF": ["representations/tfidf.py", "models/tfidf_classifier.py"],
    "03 — Embeddings + Neural Network": [
        "representations/embeddings.py",
        "models/neural_network.py",
        "evaluation/similarity.py",
    ],
    "04 — RNN": ["representations/sequences.py", "models/rnn.py"],
    "05 — Attention": ["models/attention.py", "models/rnn_attention.py"],
    "06 — Transformer": ["models/self_attention.py", "models/transformer.py"],
}
SKIP = {
    ".venv",
    ".uv-cache",
    ".deps-cache",
    ".npm-cache",
    "node_modules",
    ".next",
    "__pycache__",
    ".pytest_cache",
    ".ruff_cache",
    ".git",
    ".ipynb_checkpoints",
}


def tree_lines(directory, prefix=""):
    entries = sorted(
        (
            p
            for p in directory.iterdir()
            if p.name not in SKIP
            and not p.name.endswith((".tsbuildinfo", ".sqlite3", ".sqlite3-wal", ".sqlite3-shm"))
        ),
        key=lambda p: (not p.is_dir(), p.name),
    )
    lines = []
    for index, entry in enumerate(entries):
        last = index == len(entries) - 1
        lines.append(
            prefix + ("└── " if last else "├── ") + entry.name + ("/" if entry.is_dir() else "")
        )
        if entry.is_dir():
            lines.extend(tree_lines(entry, prefix + ("    " if last else "│   ")))
    return lines


def audit():
    report = [
        "# Final directory tree and student TODO inventory",
        "",
        "Generated by `scripts/audit_student_ml.py`. Dependencies, caches, and runtime databases are omitted.",
        "",
        "```text",
        ROOT.name + "/",
        *tree_lines(ROOT),
        "```",
        "",
    ]
    covered = set()
    count = 0
    for experiment, paths in EXPERIMENTS.items():
        report.extend([f"## Experiment {experiment}", ""])
        for relative in paths:
            path = ROOT / "ml/src" / relative
            covered.add(path)
            source = path.read_text(encoding="utf-8")
            module = ast.parse(source)
            for node in ast.walk(module):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    assert MARKER in (ast.get_docstring(node) or ""), (path, node.name)
                    assert len(node.body) == 2 and isinstance(node.body[1], ast.Raise), (
                        path,
                        node.name,
                    )
                    exception = node.body[1].exc
                    assert isinstance(exception, ast.Call) and isinstance(exception.func, ast.Name)
                    assert exception.func.id == "StudentMLNotImplemented", (path, node.name)
                    count += 1
                    report.append(
                        f"- `{path.relative_to(ROOT).as_posix()}:{node.lineno + 1}` — `{node.name}` — {MARKER}"
                    )
            assert not any(
                isinstance(node, (ast.For, ast.While, ast.ListComp)) for node in ast.walk(module)
            )
        number = experiment[:2]
        notebook = next((ROOT / "ml/notebooks").glob(f"{number}_*.ipynb"))
        document = json.loads(notebook.read_text(encoding="utf-8"))
        nbformat.validate(document)
        assert document["nbformat"] == 4
        for cell in document["cells"]:
            source = "".join(cell["source"])
            if cell["cell_type"] == "code":
                assert not source.strip() and not cell["outputs"]
            elif MARKER in source:
                count += 1
                title = source.splitlines()[0].lstrip("# ")
                report.append(f"- `{notebook.relative_to(ROOT).as_posix()}` — {title} — {MARKER}")
        test = next((ROOT / "ml/tests").glob(f"test_{number}_*.py"))
        assert MARKER in test.read_text(encoding="utf-8")
        count += 1
        report.extend(
            [f"- `{test.relative_to(ROOT).as_posix()}:1` — Student-owned tests — {MARKER}", ""]
        )
    for path in (ROOT / "ml/src").rglob("*.py"):
        if path.name not in {"__init__.py", "contracts.py"}:
            assert path in covered, f"Unreviewed ML source: {path}"
    report.extend(
        [
            "## Shared infrastructure references",
            "",
            "The exception message in `ml/src/contracts.py` and its backend/frontend tests and documentation reference the marker; they are not algorithm tasks.",
            "",
            f"Total student work markers: **{count}**. All algorithm bodies remain raising stubs; all notebook code cells are empty.",
            "",
        ]
    )
    target = ROOT / "docs/STUDENT_TODO_INVENTORY.md"
    target.write_text("\n".join(report), encoding="utf-8")
    print("\n".join(report))


if __name__ == "__main__":
    import sys

    sys.stdout.reconfigure(encoding="utf-8")
    audit()
